/** Every icon offered when picking a category or goal icon: sample set, India set, then finance set (no repeats). */
export const categoryIconCatalog: readonly (readonly [string, string])[] = (() => {
  const seen = new Set<string>();
  return [...categoryIcons, ...indiaCategoryIcons, ...financeCategoryIcons].filter(([n]) => {
    if (seen.has(n)) return false;
    seen.add(n);
    return true;
  });
})();
